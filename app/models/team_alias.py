def resolve_team(name: str) -> str:
    """把球队别名解析为数据里的规范名；无匹配则原样返回。

    参数：
    - name: 球队名（可能是简称或全名）
    """
    if not name:
        return name
    return TEAM_ALIASES.get(name.strip(), name)
